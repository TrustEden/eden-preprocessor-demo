  Spell({
    required this.name,
    required this.level,
    required this.school,
    required this.castingTime,
    required this.range,
    required this.components,
    required this.duration,
    this.concentration = false,
    this.ritual = false,
    required this.classes,
    required this.description,
    this.higherLevels = '',
    required this.source,
  });
}

