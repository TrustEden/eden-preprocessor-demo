// Helper functions
List<Spell> getSpellsByClass(String className) {
  final allSpells = [...cantrips, ...level1Spells];
  return allSpells.where((spell) => spell.classes.contains(className)).toList();
}

List<Spell> getSpellsBySchool(String school) {
  final allSpells = [...cantrips, ...level1Spells];
  return allSpells.where((spell) => spell.school == school).toList();
}

List<Spell> getSpellsByLevel(int level) {
  return spellsByLevel[level] ?? [];
}

List<Spell> getRitualSpells() {
  final allSpells = [...cantrips, ...level1Spells];
  return allSpells.where((spell) => spell.ritual).toList();
}

List<Spell> getConcentrationSpells() {
  final allSpells = [...cantrips, ...level1Spells];
  return allSpells.where((spell) => spell.concentration).toList();
}
